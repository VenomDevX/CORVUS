"""Voice Studio: text-to-voiceover generation (ElevenLabs-style, local-first).

Two engines:
  edge  - Microsoft Edge neural voices via edge-tts (300+ voices/accents,
          needs internet, no account or key). Produces MP3.
  piper - Fully-offline neural TTS. Voice models (~60MB) download once from
          Hugging Face into %LOCALAPPDATA%/Corvus/piper-voices and then run
          on CPU with no network. Produces WAV.

Long texts are split into sentences with the same SentenceChunker the live
voice pipeline uses, synthesized sequentially (gentle on CPU/commit), and the
segments concatenated: MP3 frames concatenate cleanly; Piper PCM is joined
and wrapped in a single WAV header.
"""

