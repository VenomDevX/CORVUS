# Voices are synthesized sentence-per-request; very long sentences are fine,
# but chunking keeps memory flat and lets errors surface early.
_HF_BASE = "https://huggingface.co/rhasspy/piper-voices/resolve/main"


@dataclass(frozen=True)
class PiperVoiceInfo:
    id: str          # e.g. "en_US-amy-medium"
    label: str       # human name
    language: str    # e.g. "English (US)"
    gender: str
    size_mb: int

    @property
    def hf_path(self) -> str:
        lang, name, quality = self.id.split("-", 2)
        family = lang.split("_")[0]
        return f"{_HF_BASE}/{family}/{lang}/{name}/{quality}/{self.id}"


# Curated offline catalog: every entry verified to exist in rhasspy/piper-voices.
